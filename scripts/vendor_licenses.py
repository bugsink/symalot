#!/usr/bin/env python3
"""Bundle notices from the exact Cargo dependencies used to build a release."""

import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import urllib.request


ROOT = Path(__file__).resolve().parent.parent
NOTICE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|AUTHORS?|COPYRIGHT)([._-].*)?$", re.I)


def main():
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--format-version", "1"], cwd=ROOT, text=True,
    ))
    packages = [package for package in metadata["packages"] if package["name"] != "symalot"]
    apache = next(Path(package["manifest_path"]).parent / "LICENSE-APACHE"
                  for package in packages if package["name"] == "pyo3")
    fetched = {}
    with tempfile.TemporaryDirectory(prefix="symalot-licenses-") as temporary:
        output = Path(temporary) / "licenses"
        output.mkdir()
        for package in packages:
            source = Path(package["manifest_path"]).parent
            target = output / f'{package["name"]}-{package["version"]}'
            target.mkdir()
            files = [path for path in source.rglob("*") if path.is_file() and NOTICE.fullmatch(path.name)]
            if package.get("license_file"):
                declared = (source / package["license_file"]).resolve()
                if declared.is_file() and declared.is_relative_to(source.resolve()) and declared not in files:
                    files.append(declared)
            license_files = [path for path in files if path.name.upper().startswith(("LICENSE", "LICENCE", "COPYING"))]
            provenance = {
                "crate": package["name"], "version": package["version"],
                "source": package["source"], "repository": package.get("repository"),
                "crate_archive": f'https://crates.io/api/v1/crates/{package["name"]}/{package["version"]}/download',
                "authors": package.get("authors", []), "license_expression": package.get("license"),
                "files_copied_from_crate": sorted(str(path.relative_to(source)) for path in files),
            }
            vcs = source / ".cargo_vcs_info.json"
            if vcs.is_file():
                provenance["vcs"] = json.loads(vcs.read_text())
            for path in files:
                destination = target / path.relative_to(source)
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(path, destination)
            if not license_files:
                if package["name"].startswith("symbolic-"):
                    url = f'https://raw.githubusercontent.com/getsentry/symbolic/{package["version"]}/LICENSE'
                    if url not in fetched:
                        request = urllib.request.Request(url, headers={"User-Agent": "bugsink/symalot license bundling"})
                        with urllib.request.urlopen(request, timeout=30) as response:
                            fetched[url] = response.read()
                    (target / "LICENSE").write_bytes(fetched[url])
                    provenance["license_from_upstream_release"] = url
                elif "Apache-2.0" in (package.get("license") or "").split(" OR "):
                    shutil.copyfile(apache, target / "LICENSE-APACHE")
                    provenance["selected_license"] = "Apache-2.0"
                    provenance["license_text_from"] = "pyo3/LICENSE-APACHE (standard Apache-2.0 text)"
                else:
                    raise RuntimeError(f'No license text for {package["name"]} {package["version"]}')
            (target / "SOURCE.json").write_text(json.dumps(provenance, indent=2, sort_keys=True) + "\n")
        (output / "README.md").write_text(
            "# Third-party notices\n\n"
            "Generated by scripts/vendor_licenses.py from cargo metadata --locked.\n"
            "Each directory identifies an exact dependency version, including build\n"
            "and target-specific dependencies. SOURCE.json records the published crate,\n"
            "authors, declared license, copied paths, and any fallback source.\n\n"
            "Symbolic crates omitting their license file use the upstream release's\n"
            "LICENSE. Other crates omitting license text select Apache-2.0 only when\n"
            "explicitly offered as a standalone alternative in their Cargo metadata.\n"
            "Their notices and authorship are preserved alongside the standard text.\n\n"
            "These notices ship in wheels and source distributions. Release builds\n"
            "regenerate them to follow dependency updates; do not edit generated files.\n"
        )
        destination = ROOT / "licenses"
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(output, destination)
    print(f"Bundled dependency notices for {len(packages)} locked crates.")


if __name__ == "__main__":
    main()
